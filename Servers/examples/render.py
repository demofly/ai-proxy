#!/usr/bin/env python3
"""Render public configuration examples locally, without reading live inventory."""
import argparse
import ipaddress
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

import yaml

HERE = Path(__file__).resolve().parent
DEPLOY = HERE.parent / 'deploy'


def load(path):
    return yaml.safe_load(path.read_text(encoding='utf-8'))


def flatten(tasks):
    for task in tasks:
        yield task
        for section in ('block', 'rescue', 'always'):
            yield from flatten(task.get(section, []))


def fact(tasks, key):
    matches = [t for t in flatten(tasks) if key in t.get('ansible.builtin.set_fact', {})]
    if len(matches) != 1:
        raise ValueError(f'Expected one set_fact for {key}, found {len(matches)}')
    return {'name': matches[0]['name'], 'ansible.builtin.set_fact': matches[0]['ansible.builtin.set_fact']}


def build(output):
    # This is the ONLY inventory file read. No inventory.yml, passwd, tls/,
    # secrets/, controller facts or remote files are used by this generator.
    inventory = load(DEPLOY / 'inventory.yml.sample')
    for group in inventory['all']['children'].values():
        for host in group.get('hosts', {}).values():
            address = ipaddress.ip_address(host['ansible_host'])
            if not any(address in ipaddress.ip_network(network) for network in (
                    '192.0.2.0/24', '198.51.100.0/24', '203.0.113.0/24')):
                raise ValueError('Public examples require documentation-only node addresses')
    common = inventory['all']['vars']
    common.update(ansible_connection='local', ansible_python_interpreter=sys.executable,
                  ansible_memtotal_mb=961, ansible_processor_vcpus=2,
                  ansible_default_ipv4={'interface': 'eth0'}, ansible_os_family='Debian',
                  ansible_managed='PUBLIC EXAMPLE — generated by Servers/examples/render.py',
                  squid_transit_tls=True, nginx_on_443=True, _proxy_nginx_needed=True,
                  mem_system_reserved_mb=241, mem_foreign_effective_mb=0,
                  squid_chain='SQUID-PROXY', iptables_rules_path='/etc/iptables/aiproxy-upstream.rules',
                  _crowdsec_local_config={})
    access = inventory['all']['children']['access_proxies']['vars']
    access.update(https_proxy_enabled=True, https_proxy_hostname='proxy.example.com',
                  https_proxy_acme_enabled=True, https_proxy_acme_email='admin@example.com',
                  enable_keepalived=True, keepalived_auth_pass='DEMOONLY')
    # Public, deliberately predictable fake secret: ee + 16 zero bytes + max.ru.
    common['mtproxy_secret_resolved'] = 'ee' + '00' * 16 + 'max.ru'.encode('ascii').hex()
    source = load(DEPLOY / 'playbook.yml')[0]
    resources = load(DEPLOY / 'tasks/resource-limits.yml')
    dns = load(DEPLOY / 'roles/dns_resolver/tasks/main.yml')
    tasks = [fact(source['pre_tasks'], key) for key in (
        'cpu_cores', '_proxy_enabled_services', '_proxy_minimum_plan', '_proxy_budget',
        'mem_allocatable_mb', '_proxy_memory_plan', 'mem_squid_mb', 'squid_workers')]
    tasks += [fact(resources, '_proxy_resource_units'), fact(dns, '_dns_threads'),
              fact(dns, '_dns_allowed_clients')]
    tasks.append({'name': 'Подготовить локальный контекст примера', 'ansible.builtin.set_fact': {
        'dns_allowed_clients': "{{ groups.access_proxies | map('extract', hostvars, 'ansible_host') | list }}",
        '_dns_forwarders': "{{ groups.upstreams | map('extract', hostvars, 'ansible_host') | list if proxy_role == 'access' else dns_servers }}",
        '_https_proxy_acme_cluster': "{{ groups.access_proxies | https_proxy_acme_cluster(hostvars, inventory_hostname) if proxy_role == 'access' else {} }}",
    }})
    manifest = []

    def add(target, *, template=None, content=None, source_file=None, original=None, when=None, label=None):
        # Keep the four historical example paths; other paths mirror the server.
        aliases = {'/etc/squid/squid.conf': 'squid.conf', '/etc/keepalived/keepalived.conf': 'keepalived.conf'}
        relative = aliases.get(target, target.removeprefix('/etc/').lstrip('/'))
        dest = str(output / '{{ proxy_role }}' / relative)
        condition = when or 'true'
        tasks.append({'name': 'Создать каталог примера ' + target, 'ansible.builtin.file': {
            'path': str(Path(dest).parent), 'state': 'directory', 'mode': '0755'}, 'when': condition})
        action = {'name': 'Сформировать пример ' + target, 'when': condition}
        if template:
            action['ansible.builtin.template'] = {'src': str(DEPLOY / template), 'dest': dest, 'mode': '0644'}
        elif source_file:
            action['ansible.builtin.copy'] = {'src': str(DEPLOY / source_file), 'dest': dest, 'mode': '0644'}
        else:
            action['ansible.builtin.copy'] = {'content': content, 'dest': dest, 'mode': '0644'}
        tasks.append(action)
        manifest.append({'file': relative, 'target': target, 'source': original or template,
                         'when': condition, 'note': label or ''})

    for template, target, when in (
        ('templates/squid-access.conf.j2', '/etc/squid/squid.conf', "proxy_role == 'access'"),
        ('templates/squid-upstream.conf.j2', '/etc/squid/squid.conf', "proxy_role == 'upstream'"),
        ('templates/00-sni-router.conf.j2', '/etc/nginx/stream.d/00-sni-router.conf', None),
        ('templates/10-aiproxy-capacity.conf.j2', '/etc/nginx/stream.d/10-aiproxy-capacity.conf', None),
        ('templates/aiproxy.slice.j2', '/etc/systemd/system/aiproxy.slice', None),
        ('templates/aiproxy-health.sh.j2', '/usr/local/sbin/aiproxy-check-squid', None),
        ('templates/logrotate-squid.j2', '/etc/logrotate.d/squid', "proxy_role == 'access'"),
        ('templates/keepalived.conf.j2', '/etc/keepalived/keepalived.conf', "proxy_role == 'access'"),
        ('templates/check_and_restart_squid.sh.j2', '/etc/keepalived/check_and_restart_squid.sh', "proxy_role == 'access'"),
        ('roles/dns_resolver/templates/unbound.conf.j2', '/etc/unbound/unbound.conf', None),
        ('roles/crowdsec/templates/acquis.yaml.j2', '/etc/crowdsec/acquis.d/aiproxy.yaml', None),
        ('roles/crowdsec/templates/whitelist-infrastructure.yaml.j2', '/etc/crowdsec/parsers/s02-enrich/whitelist-infrastructure.yaml', None),
        ('roles/nginx/templates/10-aiproxy-upstreams.conf.j2', '/etc/nginx/stream.d/10-aiproxy-upstreams.conf', "proxy_role == 'access'"),
        ('roles/nginx/templates/sni-map.d/aiproxy.conf.j2', '/etc/nginx/stream.d/sni-map.d/aiproxy.conf', "proxy_role == 'access'"),
        ('roles/nginx/templates/11-aiproxy-https-proxy.conf.j2', '/etc/nginx/stream.d/11-aiproxy-https-proxy.conf', "proxy_role == 'access'"),
        ('roles/nginx/templates/sni-map.d/aiproxy-https-proxy.conf.j2', '/etc/nginx/stream.d/sni-map.d/aiproxy-https-proxy.conf', "proxy_role == 'access'"),
        ('roles/nginx/templates/aiproxy-https-acme.conf.j2', '/etc/nginx/conf.d/aiproxy-https-acme.conf', "proxy_role == 'access'"),
        ('roles/mtproxy/templates/nginx-mtproxy-stream.conf.j2', '/etc/nginx/stream.d/10-mtproxy-tls.conf', "proxy_role == 'upstream'"),
        ('roles/mtproxy/templates/nginx-squid-tls-term.conf.j2', '/etc/nginx/stream.d/20-squid-tls-term.conf', "proxy_role == 'upstream'"),
        ('roles/mtproxy/templates/sni-map.d/mtproxy.conf.j2', '/etc/nginx/stream.d/sni-map.d/mtproxy.conf', "proxy_role == 'upstream'"),
        ('roles/mtproxy/templates/sni-map.d/squid.conf.j2', '/etc/nginx/stream.d/sni-map.d/squid.conf', "proxy_role == 'upstream'"),
        ('roles/mtproxy/templates/mtg.toml.j2', '/etc/mtproxy/mtg.toml', "proxy_role == 'upstream'"),
        ('roles/mtproxy/templates/users.txt.j2', '/etc/mtproxy/users.txt', "proxy_role == 'upstream'"),
        ('templates/nftables-upstream.conf.j2', '/etc/nftables.conf', "proxy_role == 'upstream'"),
        ('templates/iptables-upstream.rules.j2', '/etc/iptables/aiproxy-upstream.rules', "proxy_role == 'upstream'"),
        ('templates/ip6tables-upstream.rules.j2', '/etc/iptables/aiproxy-upstream-v6.rules', "proxy_role == 'upstream'"),
    ):
        add(target, template=template, when=when)

    # Inline copy.content is as much deployment configuration as *.j2.
    # Read its actual body rather than maintaining a parallel hand-written copy.
    inline_sources = {
        'playbook.yml': source['tasks'],
        'tasks/health.yml': load(DEPLOY / 'tasks/health.yml'),
        'tasks/shared-firewall.yml': load(DEPLOY / 'tasks/shared-firewall.yml'),
        'roles/crowdsec/tasks/main.yml': load(DEPLOY / 'roles/crowdsec/tasks/main.yml'),
        'roles/dns_resolver/tasks/main.yml': dns,
        'roles/mtproxy/tasks/daemon.yml': load(DEPLOY / 'roles/mtproxy/tasks/daemon.yml'),
        'roles/nginx/tasks/https-proxy-certificate.yml': load(DEPLOY / 'roles/nginx/tasks/https-proxy-certificate.yml'),
    }
    targets = {
        '/etc/security/limits.d/99-proxy.conf', '/etc/systemd/system/squid.service.d/limits.conf',
        '/etc/systemd/system/nginx.service.d/10-aiproxy-memory.conf',
        '/etc/systemd/system/unbound.service.d/memory-limit.conf',
        '/etc/apt/apt.conf.d/20auto-upgrades', '/etc/apt/apt.conf.d/52aiproxy-unattended-upgrades',
        '/etc/apt/sources.list.d/crowdsec_crowdsec.list', '/etc/crowdsec/config.yaml.local',
        '/etc/systemd/system/crowdsec.service.d/10-aiproxy-memory.conf',
        '/etc/systemd/system/crowdsec-firewall-bouncer.service.d/memory-limit.conf',
        '/etc/systemd/resolved.conf.d/no-stub.conf', '/etc/resolv.conf',
        '/etc/systemd/system/mtg.service', '/etc/letsencrypt/renewal-hooks/deploy/10-aiproxy-nginx',
        '/etc/shared-host/matrix-ports.nft', '/etc/systemd/system/aiproxy-shared-ports.service',
        '/etc/systemd/system/aiproxy-firewall.service',
    }
    seen = set()
    for origin, items in inline_sources.items():
        for task in flatten(items):
            body = task.get('ansible.builtin.copy', {})
            target = body.get('dest')
            if target not in targets or target in seen or 'content' not in body:
                continue
            seen.add(target)
            upstream = target.endswith(('/mtg.service', '/aiproxy-firewall.service'))
            access_only = '/letsencrypt/' in target
            add(target, content=body['content'], original=origin,
                when="proxy_role == 'upstream'" if upstream else "proxy_role == 'access'" if access_only else None)
    if seen != targets:
        raise ValueError(f'Missing inline configuration: {targets - seen}')
    for task in inline_sources['tasks/health.yml']:
        for unit in task.get('loop', []):
            add('/etc/systemd/system/' + unit['name'], content=unit['content'], original='tasks/health.yml')
    limits = next(t['ansible.builtin.copy']['content'] for t in resources if 'ansible.builtin.copy' in t)
    for name, key in (('squid', 'mem_squid_mb'), ('nginx', 'mem_nginx_mb'), ('unbound', 'mem_unbound_mb'),
                      ('haveged', 'mem_haveged_mb'), ('aiproxy-health', 'mem_health_mb'),
                      ('crowdsec', 'mem_crowdsec_mb'), ('crowdsec-firewall-bouncer', 'mem_crowdsec_bouncer_mb'),
                      ('mtg', 'mem_mtproxy_mb'), ('keepalived', 'mem_keepalived_mb')):
        when = "proxy_role == 'upstream'" if name == 'mtg' else "proxy_role == 'access'" if name == 'keepalived' else None
        add(f'/etc/systemd/system/{name}.service.d/zz-aiproxy-resources.conf',
            content=limits.replace('item.name', "'" + name + ".service'").replace('item.memory_mb', key),
            original='tasks/resource-limits.yml', when=when)
    sysctl_content = '# ai-proxy settings; other host settings omitted.\n'
    for task in source['tasks']:
        if 'ansible.posix.sysctl' not in task:
            continue
        entries = task.get('loop', [task['ansible.posix.sysctl']])
        block = ''.join(item['name'] + ' = ' + item['value'] + '\n' for item in entries)
        if task.get('when'):
            block = '{% if ' + task['when'] + ' %}\n' + block + '{% endif %}\n'
        sysctl_content += block
    add('/etc/sysctl.conf', content=sysctl_content, original='playbook.yml')
    ssh = next(t['ansible.builtin.lineinfile']['line'] for t in source['tasks']
               if t.get('ansible.builtin.lineinfile', {}).get('path') == '/etc/ssh/sshd_config')
    add('/etc/ssh/sshd_config', content='# Only the ai-proxy setting; not a complete sshd_config.\n' + ssh + '\n',
        original='playbook.yml', label='Только управляемая директива, остальные настройки SSH сохраняются.')
    # A package-owned nginx.conf cannot be reproduced from a live host. Assemble
    # a standalone example with the deployment's actual managed lines/includes.
    nginx_tasks = load(DEPLOY / 'roles/nginx/tasks/main.yml')
    lines = [t['ansible.builtin.lineinfile']['line'] for t in nginx_tasks if 'ansible.builtin.lineinfile' in t]
    def nginx_line(prefix):
        return next(line for line in lines if line.lstrip().startswith(prefix))
    add('/etc/nginx/nginx.conf', content='\n'.join([
        '# Standalone public example; package-owned host directives are not copied.',
        'load_module /usr/lib/nginx/modules/ngx_stream_module.so;', 'user www-data;',
        nginx_line('worker_processes'), nginx_line('worker_rlimit_nofile'), 'pid /run/nginx.pid;',
        'events {', nginx_line('worker_connections'), '}',
        'http {', '    include /etc/nginx/conf.d/*.conf;', '}',
        'stream {', '    include /etc/nginx/stream.d/*.conf;', '}', '']),
        original='roles/nginx/tasks/main.yml', label='Самостоятельный пример базового nginx.conf; пакетные и чужие настройки не копируются.')
    for target, origin in (('/usr/local/sbin/aiproxy-apply-shared-ports', 'scripts/apply-shared-ports.py'),):
        add(target, source_file=origin, original=origin)
    add('/etc/shared-host/aiproxy-firewall-backend', content="{{ 'ufw' if proxy_role == 'access' else 'nftables' }}\n",
        original='playbook.yml', label='Вариант UFW на access, nftables на upstream; iptables приведён как альтернатива.')
    tasks.append({'name': 'Сохранить расчёт ресурсов примера', 'ansible.builtin.copy': {
        'dest': str(output / '{{ proxy_role }}' / 'resources.json'), 'mode': '0644',
        'content': "{{ {'ram_mb': ansible_memtotal_mb, 'system_reserved_mb': mem_system_reserved_mb, 'budget': _proxy_budget, 'plan': _proxy_memory_plan, 'units': _proxy_resource_units} | to_nice_json }}\n"}})
    play = [{'name': 'Сформировать публичные примеры без подключения к серверам',
             'hosts': 'access-01:upstream-01', 'connection': 'local', 'gather_facts': False,
             'become': False, 'tasks': tasks}]
    covered = {entry['source'] for entry in manifest if entry['source'].endswith('.j2')}
    templates = {str(path.relative_to(DEPLOY)) for path in DEPLOY.rglob('*.j2')}
    if templates != covered:
        raise ValueError(f'Template coverage changed: missing={templates - covered}, obsolete={covered - templates}')
    return inventory, play, manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check committed examples without modifying them')
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix='aiproxy-public-examples-') as directory:
        tmp = Path(directory)
        output = tmp / 'result'
        inventory, play, manifest = build(output)
        (tmp / 'inventory.yml').write_text(yaml.safe_dump(inventory, allow_unicode=True), encoding='utf-8')
        (tmp / 'render.yml').write_text(yaml.safe_dump(play, allow_unicode=True), encoding='utf-8')
        env = dict(os.environ, ANSIBLE_FILTER_PLUGINS=str(DEPLOY / 'filter_plugins'),
                   ANSIBLE_NOCOLOR='1', ANSIBLE_STDOUT_CALLBACK='default', ANSIBLE_CONFIG=str(tmp / 'ansible.cfg'))
        (tmp / 'ansible.cfg').write_text('[defaults]\nretry_files_enabled = False\n', encoding='utf-8')
        result = subprocess.run(['ansible-playbook', '-i', str(tmp / 'inventory.yml'), str(tmp / 'render.yml')],
                                cwd=tmp, env=env, capture_output=True, text=True)
        if result.returncode:
            sys.stderr.write(result.stdout + result.stderr)
            return result.returncode
        (output / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        generated = {p.relative_to(output): p.read_bytes().rstrip(b'\r\n') + b'\n'
                     for p in output.rglob('*') if p.is_file()}
        existing = {p.relative_to(HERE) for role in ('access', 'upstream')
                    for p in (HERE / role).rglob('*') if p.is_file()}
        obsolete = existing - generated.keys()
        if obsolete:
            print('Obsolete examples require review:\n' + '\n'.join(sorted(map(str, obsolete))))
            return 1
        differences = []
        for relative, content in generated.items():
            destination = HERE / relative
            if not destination.exists() or destination.read_bytes().replace(b'\r\n', b'\n') != content:
                differences.append(str(relative))
                if not args.check:
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    destination.write_bytes(content)
        if args.check and differences:
            print('Examples need regeneration:\n' + '\n'.join(differences))
            return 1
        print(f'{len(generated)} public example files; ' + ('up to date' if args.check else f'{len(differences)} updated'))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
